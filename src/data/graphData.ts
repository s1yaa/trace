export function getConnectedEntities(entityId: string): Entity[] {
  const connectedIds = new Set<string>();
  GRAPH_RELATIONSHIPS.forEach(rel => {
    if (rel.sourceEntityId === entityId) connectedIds.add(rel.targetEntityId);
    if (rel.targetEntityId === entityId) connectedIds.add(rel.sourceEntityId);
  });
  return GRAPH_ENTITIES.filter(e => connectedIds.has(e.id));
}

export function getEntityById(id: string): Entity | undefined {
  return GRAPH_ENTITIES.find(e => e.id === id);
}
